function apiSame(mixed $expected, mixed $actual, string $message = ''): void
{
    if ($expected !== $actual) {
        throw new RuntimeException($message . ' Expected ' . var_export($expected, true) . '; got ' . var_export($actual, true));
    }
}

function apiCheck(bool $condition, string $message): void
{
    if (!$condition) {
        throw new RuntimeException($message);
    }
}

function apiError(Response $response, int $status, ?string $code = null): void
{
    apiSame($status, $response->status);
    apiSame(['error'], array_keys($response->body));
    apiSame(['code', 'message', 'requestId'], array_keys($response->body['error']));
    if ($code !== null) {
        apiSame($code, $response->body['error']['code']);
    }
    apiCheck(preg_match('/^[a-f0-9]{24}$/D', $response->body['error']['requestId']) === 1, 'Error request ID must be bounded and generated by the service.');
    apiSame($response->body['error']['requestId'], $response->headers['X-Request-Id'] ?? null);
}

function apiDereference(array $schema, array $document): array
{
    if (!isset($schema['$ref'])) {
        return $schema;
    }
    apiCheck(str_starts_with($schema['$ref'], '#/'), 'Contract fixtures support local references only.');
    $resolved = $document;
    foreach (explode('/', substr($schema['$ref'], 2)) as $part) {
        $key = str_replace(['~1', '~0'], ['/', '~'], $part);
        apiCheck(isset($resolved[$key]), 'Unresolved OpenAPI reference: ' . $schema['$ref']);
        $resolved = $resolved[$key];
    }
    return apiDereference($resolved, $document);
}

/** Validate the response-schema features used by this contract, not a general JSON Schema engine. */
function apiValidateSchema(mixed $value, array $schema, array $document, string $at = 'response'): void
{
    $schema = apiDereference($schema, $document);
    if (isset($schema['anyOf'])) {
        foreach ($schema['anyOf'] as $option) {
            try {
                apiValidateSchema($value, $option, $document, $at);
                return;
            } catch (RuntimeException) {
                // Try the next declared alternative (e.g. a snapshot object or null).
            }
        }
        throw new RuntimeException($at . ' does not match any documented alternative.');
    }
    $types = (array) ($schema['type'] ?? []);
    $matches = [];
    foreach ($types as $type) {
        $matches[] = match ($type) {
            'object' => $value instanceof stdClass,
            'array' => is_array($value),
            'string' => is_string($value),
            'integer' => is_int($value),
            'number' => is_int($value) || is_float($value),
            'boolean' => is_bool($value),
            'null' => $value === null,
            default => throw new RuntimeException('Unsupported fixture schema type: ' . $type),
        };
    }
    apiCheck($types === [] || in_array(true, $matches, true), $at . ' has an undocumented JSON type.');
    if (array_key_exists('const', $schema)) {
        apiSame($schema['const'], $value, $at);
    }
    if (isset($schema['enum'])) {
        apiCheck(in_array($value, $schema['enum'], true), $at . ' is outside its documented enum.');
    }
    if (is_int($value) || is_float($value)) {
        apiCheck(!isset($schema['minimum']) || $value >= $schema['minimum'], $at . ' is below its minimum.');
        apiCheck(!isset($schema['maximum']) || $value <= $schema['maximum'], $at . ' is above its maximum.');
    }
    if (is_string($value)) {
        $length = preg_match_all('/./us', $value);
        apiCheck(!isset($schema['minLength']) || $length >= $schema['minLength'], $at . ' is too short.');
        apiCheck(!isset($schema['maxLength']) || $length <= $schema['maxLength'], $at . ' is too long.');
        apiCheck(!isset($schema['pattern']) || preg_match('~' . str_replace('~', '\\~', $schema['pattern']) . '~uD', $value) === 1, $at . ' fails its documented pattern.');
    }
    if ($value instanceof stdClass) {
        $properties = get_object_vars($value);
        foreach ($schema['required'] ?? [] as $key) {
            apiCheck(array_key_exists($key, $properties), $at . ' is missing ' . $key);
        }
        foreach ($properties as $key => $child) {
            if (isset($schema['properties'][$key])) {
                apiValidateSchema($child, $schema['properties'][$key], $document, $at . '.' . $key);
            } else {
                apiCheck(($schema['additionalProperties'] ?? true) !== false, $at . ' exposes undocumented property ' . $key);
            }
        }
    }
    if (is_array($value)) {
        apiCheck(!isset($schema['maxItems']) || count($value) <= $schema['maxItems'], $at . ' has too many items.');
        foreach ($value as $index => $child) {
            apiValidateSchema($child, $schema['items'] ?? [], $document, $at . '[' . $index . ']');
        }
    }
}

